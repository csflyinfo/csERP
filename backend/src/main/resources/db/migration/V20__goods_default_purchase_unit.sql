-- ============================================
-- V20: 商品档案增加「默认采购单位」
--
-- 业务规则：
--   · 若商品设置了 default_purchase_unit（存单位名称，如「箱」），
--     则采购订单 / 采购退货申请添加商品时，采购单位默认取该值；
--   · 未设置时沿用现有逻辑（大单位 → 中单位 → 小单位 优先级）。
--
-- 存单位名称而非 level，因为：
--   1. 前端 unitConfig 里 unitName 是用户自定义的（箱/瓶/件…），name 比 level 更直观；
--   2. 便于在商品档案下拉里直接选已启用的单位。
-- ============================================

ALTER TABLE base_goods ADD COLUMN default_purchase_unit VARCHAR(50);
